use MeuMouse\WC_Custom_Installments\Core\Init;
use MeuMouse\WC_Custom_Installments\Core\Onboarding;

defined('ABSPATH') || exit;

// Composer autoloader. Generated by the build; absent only in a broken install.
$wc_custom_installments_autoload = plugin_dir_path( __FILE__ ) . 'admin/vendor/autoload.php';

if ( file_exists( $wc_custom_installments_autoload ) ) {
	require_once $wc_custom_installments_autoload;
}

$wc_custom_installments_plugin_version = '6.0.0';

/**
 * Flag a fresh activation so the first admin request opens the setup wizard.
 *
 * Nothing is written beyond the flag: activation must not touch the store's
 * pricing, and must not contact any external service.
 */
register_activation_hook( __FILE__, function() {
	if ( class_exists( Onboarding::class ) ) {
		Onboarding::on_activation();
	}
});

/**
 * Deactivation clears scheduled events only.
 *
 * Nothing is deleted. Turning a plugin off is not the same as uninstalling it,
 * and a store owner who deactivates to debug a theme conflict expects to find
 * their settings intact.
 */
register_deactivation_hook( __FILE__, function() {
	foreach ( array( 'wc_custom_installments_purge_logs_event' ) as $hook ) {
		wp_clear_scheduled_hook( $hook );
	}
});

// Initialize the plugin.
if ( class_exists( Init::class ) ) {
	new Init( __FILE__, $wc_custom_installments_plugin_version );
}